-- Nim Dvir link shortener
-- Applied to an existing Supabase project with isolated table names.
-- If SHORTENER_ADMIN_SECRET changes, replace the SHA-256 hash in every admin policy
-- (alter policy ... using/with check), then redeploy so Vercel picks up the new value.
-- link_type 'url' redirects; 'path' stores a local Windows path and shows it as plain text.

create table if not exists public.short_links (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9_-]{0,47}$'),
  destination_url text not null,
  link_type text not null default 'url',
  title text,
  is_active boolean not null default true,
  click_count bigint not null default 0 check (click_count >= 0),
  last_clicked_at timestamptz,
  created_via text,
  created_at timestamptz not null default now(),
  constraint short_links_created_via_check check (created_via is null or created_via ~ '^[a-z0-9-]{1,40}$'),
  constraint short_links_link_type_check check (link_type in ('url', 'path')),
  constraint short_links_destination_check check (
    (link_type = 'url' and destination_url ~ '^https?://')
    or (link_type = 'path' and destination_url ~ '^[A-Za-z]:[\\/]' and length(destination_url) <= 1000)
  )
);

-- Optional topic for grouping links on the admin page (added 2026-11-26).
alter table public.short_links add column if not exists topic text;
alter table public.short_links drop constraint if exists short_links_topic_check;
alter table public.short_links add constraint short_links_topic_check check (topic is null or length(topic) <= 40);

create table if not exists public.short_link_clicks (
  id bigint generated by default as identity primary key,
  link_id bigint not null references public.short_links(id) on delete cascade,
  clicked_at timestamptz not null default now(),
  referrer text,
  user_agent text,
  device_type text,
  browser text,
  os text,
  country text,
  region text,
  city text
);

create index if not exists short_link_clicks_link_id_idx on public.short_link_clicks(link_id);
create index if not exists short_link_clicks_clicked_at_idx on public.short_link_clicks(clicked_at desc);

