create schema if not exists shortener_private;
revoke all on schema shortener_private from public, anon, authenticated;

create or replace function shortener_private.rollup_click()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.short_links
  set click_count = click_count + 1,
      last_clicked_at = new.clicked_at
  where id = new.link_id;
  return new;
end;
$$;

revoke all on function shortener_private.rollup_click() from public, anon, authenticated;

drop trigger if exists short_link_click_rollup on public.short_link_clicks;
create trigger short_link_click_rollup
after insert on public.short_link_clicks
for each row execute function shortener_private.rollup_click();
