-- Nim Dvir link shortener
-- Applied to an existing Supabase project with isolated table names.
-- If SHORTENER_ADMIN_SECRET changes, replace the SHA-256 hash in every admin policy.

create table if not exists public.short_links (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9_-]{0,47}$'),
  destination_url text not null check (destination_url ~ '^https?://'),
  title text,
  is_active boolean not null default true,
  click_count bigint not null default 0 check (click_count >= 0),
  last_clicked_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.short_link_clicks (
  id bigint generated by default as identity primary key,
  link_id bigint not null references public.short_links(id) on delete cascade,
  clicked_at timestamptz not null default now(),
  referrer text,
  user_agent text,
  device_type text,
  browser text,
  os text,
  country text,
  region text,
  city text
);

create index if not exists short_link_clicks_link_id_idx on public.short_link_clicks(link_id);
create index if not exists short_link_clicks_clicked_at_idx on public.short_link_clicks(clicked_at desc);

alter table public.short_links enable row level security;
alter table public.short_link_clicks enable row level security;

revoke all on table public.short_links from anon, authenticated;
revoke all on table public.short_link_clicks from anon, authenticated;
grant select, insert, update, delete on table public.short_links to anon;
grant select, insert on table public.short_link_clicks to anon;
grant usage, select on sequence public.short_links_id_seq to anon;
grant usage, select on sequence public.short_link_clicks_id_seq to anon;

