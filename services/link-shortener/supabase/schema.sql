create schema if not exists shortener_private;
revoke all on schema shortener_private from public, anon, authenticated;

create or replace function shortener_private.rollup_click()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.short_links
  set click_count = click_count + 1,
      last_clicked_at = new.clicked_at
  where id = new.link_id;
  return new;
end;
$$;

revoke all on function shortener_private.rollup_click() from public, anon, authenticated;

drop trigger if exists short_link_click_rollup on public.short_link_clicks;
create trigger short_link_click_rollup
after insert on public.short_link_clicks
for each row execute function shortener_private.rollup_click();

-- AI connector (/mcp): OAuth clients, one-time codes and tokens (hashes only).
-- Each chat registers itself, Nim approves it with the admin passcode, and it gets its own token.
create table if not exists public.shortener_oauth_clients (
  client_id text primary key,
  client_secret_hash text,
  client_name text,
  redirect_uris text[] not null,
  redirect_host text,
  token_endpoint_auth_method text not null default 'none',
  created_at timestamptz not null default now(),
  last_used_at timestamptz
);

create table if not exists public.shortener_oauth_codes (
  code_hash text primary key,
  client_id text not null references public.shortener_oauth_clients(client_id) on delete cascade,
  redirect_uri text not null,
  code_challenge text not null,
  scope text,
  resource text,
  expires_at timestamptz not null
);

create table if not exists public.shortener_oauth_tokens (
  id bigint generated by default as identity primary key,
  client_id text not null references public.shortener_oauth_clients(client_id) on delete cascade,
  access_hash text not null unique,
  refresh_hash text unique,
  access_expires_at timestamptz not null,
  refresh_expires_at timestamptz,
  scope text,
  resource text,
  created_at timestamptz not null default now()
);
create index if not exists shortener_oauth_tokens_client_idx on public.shortener_oauth_tokens(client_id);

alter table public.shortener_oauth_clients enable row level security;
alter table public.shortener_oauth_codes enable row level security;
